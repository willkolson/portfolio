import {defineArrayMember, defineField, defineType} from 'sanity'

export const caseStudy = defineType({
  name: 'caseStudy',
  title: 'Case study',
  type: 'document',
  groups: [
    {name: 'content', title: 'Content', default: true},
    {name: 'meta', title: 'Details'},
    {name: 'seo', title: 'SEO'},
  ],
  fields: [
    defineField({name: 'title', title: 'Title', type: 'string', group: 'content', validation: (Rule) => Rule.required()}),
    defineField({
      name: 'slug',
      title: 'Slug',
      type: 'slug',
      group: 'content',
      options: {source: 'title', maxLength: 80},
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'summary',
      title: 'Summary',
      type: 'text',
      rows: 3,
      group: 'content',
      description: 'One or two sentences for cards and the meta description fallback',
      validation: (Rule) => Rule.required().max(200),
    }),
    defineField({
      name: 'coverImage',
      title: 'Cover image',
      type: 'image',
      group: 'content',
      options: {hotspot: true},
      fields: [defineField({name: 'alt', type: 'string', title: 'Alt text', validation: (Rule) => Rule.required()})],
    }),
    defineField({name: 'problem', title: 'Problem', type: 'text', rows: 4, group: 'content'}),
    defineField({name: 'hypothesis', title: 'Hypothesis / approach', type: 'text', rows: 4, group: 'content'}),
    defineField({
      name: 'results',
      title: 'Results',
      type: 'array',
      group: 'content',
      of: [defineArrayMember({type: 'metric'})],
    }),
    defineField({name: 'body', title: 'Full write-up', type: 'blockContent', group: 'content'}),
    defineField({name: 'company', title: 'Company / client', type: 'string', group: 'meta'}),
    defineField({name: 'role', title: 'Your role', type: 'string', group: 'meta'}),
    defineField({name: 'date', title: 'Date', type: 'date', group: 'meta'}),
    defineField({
      name: 'skills',
      title: 'Skills used',
      type: 'array',
      group: 'meta',
      of: [defineArrayMember({type: 'reference', to: [{type: 'skill'}]})],
    }),
    defineField({name: 'featured', title: 'Feature on homepage', type: 'boolean', group: 'meta', initialValue: false}),
    defineField({name: 'seo', title: 'SEO', type: 'seo', group: 'seo'}),
  ],
  orderings: [{title: 'Newest', name: 'dateDesc', by: [{field: 'date', direction: 'desc'}]}],
  preview: {select: {title: 'title', subtitle: 'company', media: 'coverImage'}},
})
